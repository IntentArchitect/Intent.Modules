                private static int GuardWrite(Harness harness, VersionScheme scheme, string? positional, string input, TextWriter stdout, TextWriter stderr, string repoRoot, IGitChangeProvider gitChangeProvider)
                {
                    if (HookPayload.IsReadOnlyTool(HookPayload.ToolName(input)))
                    {
                        return Allow(stderr);
                    }

                    // Codex: one apply_patch can touch several files, named inside the patch text.
                    if (ApplyPatchExtractor.Extract(input) is { } patchedFiles)
                    {
                        string? patchNote = null;
                        foreach (var file in patchedFiles)
                        {
                            var violation = IntentMetadataGuard.DescribeViolation(file.Path);
                            if (violation is null && file.Path.EndsWith(".imodspec", StringComparison.OrdinalIgnoreCase))
                            {
                                if (!ImodspecFieldGuard.IsHandEditAllowed(null, file.AddedText))
                                {
                                    violation = ImodspecSummaryDenial;
                                }
                                else
                                {
                                    violation = CheckVersionEdit(ResolvePath(repoRoot, file.Path), file.AddedText, scheme, repoRoot, gitChangeProvider, out var note);
                                    patchNote ??= note;
                                }
                            }

                            if (violation is not null)
                            {
                                return Deny(harness, stdout, stderr, violation);
                            }
                        }

                        return patchNote is null ? Allow(stderr) : AllowWithContext(harness, stdout, patchNote);
                    }

                    var path = StdinPathExtractor.Extract(input, positional);

                    if (path is null)
                    {
                        return Allow(stderr, "intent-agent-gate: could not determine a target file path from stdin or arguments; no opinion.");
                    }

                    // Intent's OWN metadata - the designer model, an application's configuration, and
                    // the record of what it generated and installed. This is the whole of what
                    // guard-write protects. Generated OUTPUT is deliberately NOT covered: hand-editing
                    // it is frequently the intended workflow - authoring a scaffolded template, writing
                    // release notes, correcting a csproj package version - and blocking it produced
                    // false positives and nothing else in real use.
                    var metadataViolation = IntentMetadataGuard.DescribeViolation(path);
                    if (metadataViolation is not null)
                    {
                        return Deny(harness, stdout, stderr, metadataViolation);
                    }

                    // ".imodspec" is field-scoped, not file-scoped: <tags>, <dependency> and the version
                    // are legitimate hand-edits; <summary>/<description> are always denied, because the
                    // Software Factory overwrites both from Application Settings on every run and
                    // discards a manual edit silently. The version is held to the same rules as setting
                    // it through the designer.
                    if (path.EndsWith(".imodspec", StringComparison.OrdinalIgnoreCase))
                    {
                        var edit = StdinEditExtractor.Extract(input);
                        var editedText = edit.WholeFileContent ?? edit.EditSnippet;
                        if (editedText is null)
                        {
                            return Allow(stderr, "intent-agent-gate: could not read the edit content; no opinion.");
                        }

                        var fullPath = ResolvePath(repoRoot, path);
                        string? currentDiskContent = null;
                        if (edit.WholeFileContent is not null && File.Exists(fullPath))
                        {
                            try
                            {
                                currentDiskContent = File.ReadAllText(fullPath);
                            }
                            catch (IOException)
                            {
                                // Fall through to the snippet-only comparison below.
                            }
                        }

                        if (!ImodspecFieldGuard.IsHandEditAllowed(currentDiskContent, editedText))
                        {
                            return Deny(harness, stdout, stderr, ImodspecSummaryDenial);
                        }

                        var versionViolation = CheckVersionEdit(fullPath, editedText, scheme, repoRoot, gitChangeProvider, out var versionNote);
                        if (versionViolation is not null)
                        {
                            return Deny(harness, stdout, stderr, versionViolation);
                        }

                        return versionNote is null ? Allow(stderr) : AllowWithContext(harness, stdout, versionNote);
                    }

                    // Everything else, including every file the Software Factory generates, is allowed
                    // and stays completely silent - zero tokens for the overwhelming common case.
                    return Allow(stderr);
                }

                private static string ResolvePath(string repoRoot, string path) =>
                    Path.IsPathRooted(path) ? path : Path.GetFullPath(Path.Combine(repoRoot, path));

                /// <summary>
                /// A hand-edit of an ".imodspec"'s "&lt;version&gt;": denied when it breaks the version
                /// rules, otherwise allowed with a reminder to load the versioning skill. Returns the
                /// denial, or null; <paramref name="note"/> carries the reminder when the version moves.
                /// </summary>
                /// <remarks>
                /// Agents bump a version by editing the file rather than through the designer - every
                /// version change in the eval runs went this way - so guarding only run_designer_script
                /// left the rules unenforced on the route actually taken. A downgrade stays allowed here:
                /// the Software Factory will not write a lower version from the designer, so this is the
                /// sanctioned route for correcting one.
                /// </remarks>
                private static string? CheckVersionEdit(string imodspecPath, string editedText, VersionScheme scheme, string repoRoot, IGitChangeProvider gitChangeProvider, out string? note)
                {
                    note = null;
                    var proposed = ModuleResolver.ReadVersionFromEditedText(editedText);
                    var current = File.Exists(imodspecPath) ? ModuleResolver.ReadVersionFromImodspecFile(imodspecPath) : null;
                    if (proposed is null || current is null || string.Equals(proposed, current, StringComparison.Ordinal))
                    {
                        return null;
                    }

                    var relative = Path.GetRelativePath(repoRoot, imodspecPath).Replace('\\', '/');
                    var headContent = gitChangeProvider.TryReadFileAtHead(repoRoot, relative);
                    var head = headContent is null ? null : ModuleResolver.ReadVersionFromImodspecContent(headContent);

                    var violation = VersionRules.Check(proposed, current, head, scheme, allowDowngrade: true);
                    if (violation is not null)
                    {
                        return violation + " " + VersionRules.SkillPointer;
                    }

                    note = $"intent-agent-gate: this edit changes the module version from '{current}' to '{proposed}'. " + VersionRules.SkillPointer;
                    return null;
                }

                private static int RunGuardVersion(string[] rest, TextReader stdin, TextWriter stdout, TextWriter stderr, string repoRoot, IGitChangeProvider gitChangeProvider)
                {
                    var (harness, scheme) = ParseGuardVersionArgs(rest);
                    return GuardVersion(harness, scheme, HookPayload.Normalize(stdin.ReadToEnd()), stdout, stderr, repoRoot, gitChangeProvider);
                }

                private static int GuardVersion(Harness harness, VersionScheme scheme, string input, TextWriter stdout, TextWriter stderr, string repoRoot, IGitChangeProvider gitChangeProvider)
                {
                    var invocation = DesignerScriptInputExtractor.Extract(input);

                    if (invocation.Script is null || VersionScriptExtractor.ExtractNewVersion(invocation.Script) is not { } newVersionText)
                    {
                        // Not a Version-setting script at all - silent allow, zero tokens.
                        return Allow(stderr);
                    }

                    if (invocation.ApplicationId is null)
                    {
                        return Allow(stderr, "intent-agent-gate: could not resolve the target module; no opinion.");
                    }

                    var moduleFolder = ModuleResolver.FindModuleFolderByApplicationId(repoRoot, invocation.ApplicationId);
                    var imodspecPath = moduleFolder is null ? null : ModuleResolver.FindImodspec(moduleFolder);
                    if (imodspecPath is null)
                    {
                        return Allow(stderr, "intent-agent-gate: could not locate the module's .imodspec; no opinion.");
                    }

                    var currentVersionText = ModuleResolver.ReadVersionFromImodspecFile(imodspecPath);
                    if (currentVersionText is null || !SemVer.TryParse(currentVersionText, out _))
                    {
                        // An invalid proposed version is still worth denying even when the current one is unreadable.
                        return SemVer.TryParse(newVersionText, out _)
                            ? Allow(stderr, "intent-agent-gate: could not read the module's current version; no opinion.")
                            : Deny(harness, stdout, stderr, $"'{newVersionText}' is not a valid semantic version (expected Major.Minor.Patch[-pre.N]).");
                    }

                    var relativeImodspec = Path.GetRelativePath(repoRoot, imodspecPath).Replace('\\', '/');
                    var headContent = gitChangeProvider.TryReadFileAtHead(repoRoot, relativeImodspec);
                    var headVersionText = headContent is null ? null : ModuleResolver.ReadVersionFromImodspecContent(headContent);

                    var violation = VersionRules.Check(newVersionText, currentVersionText, headVersionText, scheme, allowDowngrade: false);
                    return violation is null ? Allow(stderr) : Deny(harness, stdout, stderr, violation);
                }

                private static int RunCloseOut(string[] rest, TextWriter stdout, string repoRoot, IGitChangeProvider gitChangeProvider)
                {
                    var (harness, _) = ParseArgs(rest);

                    // Outside a git repository git reports nothing, so this finds no changes and
                    // stays silent - there is no other record of what this session changed.
                    var changedFiles = gitChangeProvider.GetChangedFiles(repoRoot);
                    var versionResult = ModuleVersionAuditor.Audit(repoRoot, changedFiles);
                    var otherFindings = CloseOutAuditor.Audit(repoRoot, changedFiles);

                    if (versionResult.Passed && otherFindings.Count == 0)
                    {
                        // Clean - silent, zero tokens. Close-out never blocks; see the deny/warn split.
                        return 0;
                    }

                    var messages = new List<string>();
                    if (!versionResult.Passed)
                    {
                        var moduleNames = string.Join(", ", versionResult.Violations.Select(v => v.ModuleName));
                        messages.Add(
                            $"Module(s) changed without their .imodspec version moving: {moduleNames}. " +
                            "Consult the module-version-increment skill before finishing this change.");
                    }

                    messages.AddRange(otherFindings.Select(f => $"[{f.ModuleName}] {f.Message}"));

                    stdout.WriteLine(HarnessProtocol.FormatWarning(harness, string.Join(" ", messages)));
                    return 0;
                }

                /// <summary>
                /// Allows silently. A diagnostic note goes to stderr, which every harness keeps out of
                /// the agent's context on a successful hook - it is there for the gate log.
                /// </summary>
                /// <remarks>
                /// The note used to be written as an "allow" decision, which cost tokens on every call
                /// for harnesses that run the guard on every tool (Copilot) and, worse, told Claude Code
                /// the action was pre-approved, skipping its own permission prompt.
                /// </remarks>
                private static int Allow(TextWriter stderr, string? note = null)
                {
                    if (note is not null)
                    {
                        stderr.WriteLine(note);
                    }

                    return 0;
                }

                private static int AllowWithContext(Harness harness, TextWriter stdout, string context)
                {
                    var formatted = HarnessProtocol.FormatAllowWithContext(harness, context);
                    if (formatted is not null)
                    {
                        stdout.WriteLine(formatted);
                    }

                    return 0;
                }

                private static int Deny(Harness harness, TextWriter stdout, TextWriter stderr, string reason)
                {
                    var formatted = HarnessProtocol.FormatDeny(harness, reason);
                    if (formatted is not null)
                    {
                        stdout.WriteLine(formatted);
                    }

                    stderr.WriteLine(reason);
                    return 2;
                }

                private static int Unknown(string command, TextWriter stderr)
                {
                    stderr.WriteLine($"Unknown command: {command}");
                    return 2;
                }

                private static (Harness Harness, string? Positional) ParseArgs(string[] rest)
                {
                    string? harnessValue = null;
                    string? positional = null;

                    for (var i = 0; i < rest.Length; i++)
                    {
                        if (rest[i] == "--harness" && i + 1 < rest.Length)
                        {
                            harnessValue = rest[i + 1];
                            i++;
                        }
                        else if (rest[i] == "--scheme" && i + 1 < rest.Length)
                        {
                            i++;
                        }
                        else if (!rest[i].StartsWith("--", StringComparison.Ordinal))
                        {
                            positional ??= rest[i];
                        }
                    }

                    return (HarnessProtocol.Parse(harnessValue), positional);
                }

                // Written by the Software Factory from the "Use Pre-release Versions" setting, so every
                // harness's hook command can stay identical and still enforce the configured scheme.
                // An explicit --scheme flag overrides it.
                private const VersionScheme DefaultScheme = VersionScheme.Final;

                private static (Harness Harness, VersionScheme Scheme) ParseGuardVersionArgs(string[] rest)
                {
                    var (harness, _) = ParseArgs(rest);

                    var scheme = DefaultScheme;
                    for (var i = 0; i < rest.Length; i++)
                    {
                        if (rest[i] == "--scheme" && i + 1 < rest.Length)
                        {
                            scheme = rest[i + 1] switch
                            {
                                "pre" => VersionScheme.PreRelease,
                                "final" => VersionScheme.Final,
                                _ => scheme,
                            };
                        }
                    }

                    return (harness, scheme);
                }
