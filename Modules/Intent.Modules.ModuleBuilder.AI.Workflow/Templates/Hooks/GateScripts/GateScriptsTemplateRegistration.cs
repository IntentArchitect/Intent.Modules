            /// <summary>
            /// The version rules shared by both routes to a module's version: the designer
            /// ("run_designer_script" setting the Version property) and a hand-edit of the
            /// ".imodspec"'s "&lt;version&gt;".
            /// </summary>
            public static class VersionRules
            {
                public const string SkillPointer =
                    "Load the module-version-increment skill and run its 'Is This Version Already In Flight?' check before changing the version.";

                /// <summary>
                /// Why the move from <paramref name="current"/> to <paramref name="proposed"/> breaks a
                /// rule, or null when it is allowed. <paramref name="head"/> is the version at HEAD, or
                /// null when there is none to compare with (a new module, or no git repository).
                /// </summary>
                public static string? Check(string proposedText, string currentText, string? headText, VersionScheme scheme, bool allowDowngrade)
                {
                    if (!SemVer.TryParse(proposedText, out var proposed))
                    {
                        return $"'{proposedText}' is not a valid semantic version (expected Major.Minor.Patch[-pre.N]).";
                    }

                    if (!SemVer.TryParse(currentText, out var current))
                    {
                        return null;
                    }

                    var comparison = SemVer.ComparePrecedence(proposed, current);
                    if (comparison < 0 && allowDowngrade)
                    {
                        // A deliberate correction downward. The Software Factory will not write a lower
                        // version from the designer, so the hand-edit is the sanctioned route for it.
                        return null;
                    }

                    if (comparison <= 0)
                    {
                        return $"'{proposedText}' does not sort strictly higher than the current version '{currentText}'. " +
                            "If this is a deliberate downgrade correction, the Software Factory will not regenerate a lower value " +
                            "from the designer - set the version directly in the .imodspec instead (see module-version-increment).";
                    }

                    // Double bump - has this module's version already moved against HEAD in this line of work?
                    if (headText is not null &&
                        SemVer.TryParse(headText, out var head) &&
                        SemVer.ComparePrecedence(current, head) > 0)
                    {
                        return $"This module's version already moved this line of work ('{headText}' -> '{currentText}'). " +
                            "A version moves once per line of work - see module-version-increment. If more work landed since, " +
                            "that is the same bump, not a second one.";
                    }

                    // Under pre-release versioning, dropping the "-pre.N" suffix is only legal as a
                    // promotion of the SAME core version; introducing a new core version bare is the violation.
                    var sameCore = proposed.Major == current.Major && proposed.Minor == current.Minor && proposed.Patch == current.Patch;
                    if (scheme == VersionScheme.PreRelease && proposed.PreRelease is null && !sameCore)
                    {
                        return $"Pre-release versioning is configured, so '{proposedText}' should be " +
                            $"'{proposed.Major}.{proposed.Minor}.{proposed.Patch}-pre.0'.";
                    }

                    return null;
                }
            }
