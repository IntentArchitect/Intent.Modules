        private const string GateNamespaceLine = "namespace Intent.Agent.Gate;";

        /// <summary>
        /// Joins the gate's sources into ONE self-contained file-based app.
        /// </summary>
        /// <remarks>
        /// One file rather than "#:include", because "#:include" needs .NET SDK 10.0.300 or later. On
        /// an older SDK the gate failed to compile with "Unrecognized directive 'include'", and every
        /// guarded edit was blocked by an error that said nothing about why. A single file compiles
        /// on any .NET 10 SDK. The sources stay separate constants here so each concern is readable.
        /// <para>
        /// Each source's leading "using"s are hoisted and de-duplicated, and its file-scoped
        /// namespace becomes one block-scoped namespace: C# allows no file-scoped namespace after
        /// top-level statements (CS8956). The entry point sits behind "#if !AGENT_GATE_TESTS" so the
        /// test project compiles this same file rather than a copy of it.
        /// </para>
        /// </remarks>
        private static string ComposeGate(IEnumerable<string> sources)
        {
            var usings = new SortedSet<string>(StringComparer.Ordinal);
            var bodies = new List<string>();
            var newLine = "\n";

            foreach (var source in sources)
            {
                if (source.Contains("\r\n"))
                {
                    newLine = "\r\n";
                }

                var lines = source.Replace("\r\n", "\n").Split('\n');
                var namespaceIndex = Array.IndexOf(lines, GateNamespaceLine);
                if (namespaceIndex < 0)
                {
                    throw new InvalidOperationException($"A gate source no longer starts with '{GateNamespaceLine}'; update {nameof(ComposeGate)} to match.");
                }

                foreach (var line in lines.Take(namespaceIndex).Where(line => line.Trim().Length > 0))
                {
                    if (!line.StartsWith("using ", StringComparison.Ordinal))
                    {
                        throw new InvalidOperationException($"Unexpected line before the namespace in a gate source: '{line}'.");
                    }

                    usings.Add(line);
                }

                bodies.Add(string.Join("\n", lines.Skip(namespaceIndex + 1).Select(line => line.Length == 0 ? line : "    " + line)).Trim('\n'));
            }

            var file = new List<string>
            {
                "#!/usr/bin/env dotnet",
                "#:property PublishAot=false",
                "",
                "// The Intent agent gate, generated by Intent.ModuleBuilder.AI.Workflow - regenerate rather than edit.",
                "// One self-contained file so it runs on any .NET 10 SDK: dotnet run <this file> -- <command>",
            };
            file.AddRange(usings);
            file.Add("using Intent.Agent.Gate;");
            file.Add("");
            file.Add("#if !AGENT_GATE_TESTS");
            file.Add("return Cli.Run(args, Console.In, Console.Out, Console.Error, Directory.GetCurrentDirectory());");
            file.Add("#endif");
            file.Add("");
            file.Add("namespace Intent.Agent.Gate");
            file.Add("{");
            file.Add(string.Join("\n\n", bodies));
            file.Add("}");

            return string.Join("\n", file).Replace("\n", newLine) + newLine;
        }

