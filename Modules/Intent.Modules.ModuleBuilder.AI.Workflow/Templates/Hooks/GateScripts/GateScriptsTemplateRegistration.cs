                private static int RunCore(
                    string[] args,
                    TextReader stdin,
                    TextWriter stdout,
                    TextWriter stderr,
                    string currentDirectory,
                    IGitChangeProvider? gitChangeProvider)
                {
                    var command = args.Length == 0 ? null : args[0];
                    try
                    {
                        if (command is null)
                        {
                            stderr.WriteLine("Usage: gate.cs <guard-write|guard-version|guard-tool|close-out|warm> [--harness claude|codex|cursor|github|kiro|opencode] [--scheme pre|final] [path]");
                            return 2;
                        }

                        var rest = args[1..];
                        // Outside a git repository, fall back to the folder the hook runs from - the
                        // project root. Giving up instead would switch off every guard in a folder
                        // that simply hasn't been "git init"-ed yet. Only what genuinely needs git
                        // degrades: close-out has no change list, and the double-bump check has no
                        // HEAD to compare against.
                        var repoRoot = GitRepoLocator.FindRepoRoot(currentDirectory) ?? currentDirectory;

                        if (StepsAsideFor(command, rest, ref stdin) is { } runner)
                        {
                            stderr.WriteLine($"intent-agent-gate: Claude Code's hook was run by {runner}, whose own hook decides; stepping aside.");
                            return 0;
                        }

                        return command switch
                        {
                            "warm" => 0,
                            "guard-write" => RunGuardWrite(rest, stdin, stdout, stderr, repoRoot, gitChangeProvider ?? new ProcessGitChangeProvider()),
                            "guard-version" => RunGuardVersion(rest, stdin, stdout, stderr, repoRoot, gitChangeProvider ?? new ProcessGitChangeProvider()),
                            "guard-tool" => RunGuardTool(rest, stdin, stdout, stderr, repoRoot, gitChangeProvider ?? new ProcessGitChangeProvider()),
                            "close-out" => RunCloseOut(rest, stdout, repoRoot, gitChangeProvider ?? new ProcessGitChangeProvider()),
                            _ => Unknown(command, stderr),
                        };
                    }
                    catch (Exception ex) when (command == "close-out")
                    {
                        // close-out never blocks, and a crash is no exception. A Stop hook that exits 2
                        // tells Claude Code and Codex the agent must KEEP GOING, so blocking here traps
                        // the agent in a loop of turns it can do nothing about. Say what happened and
                        // let the turn end.
                        stderr.WriteLine($"intent-agent-gate: close-out checks were skipped after an unexpected error - nothing for the agent to fix: {ex.Message}");
                        return 0;
                    }
                    catch (Exception ex)
                    {
                        // Fail closed on a genuine crash. This must be an EXPLICIT exit(2), not whatever
                        // the runtime's default unhandled-exception code is: Cursor specifically treats
                        // any non-zero code other than 2 as an allow.
                        stderr.WriteLine($"intent-agent-gate: unexpected error, blocking rather than guessing: {ex.Message}");
                        return 2;
                    }
                }

                /// <summary>
                /// The harness that ran Claude Code's copy of the gate when that harness is not Claude
                /// Code and has a hook of its own that decides, or null when this copy must decide.
                /// </summary>
                /// <remarks>
                /// Copilot CLI and Cursor also run the hooks in ".claude/settings.json", so in a repository
                /// with both folders every guarded action reached the gate twice: once through the
                /// harness's own hook and once, formatted for Claude Code, through Claude's. The foreign
                /// copy now steps aside silently - only ever Claude's, since that is the only hook file
                /// another harness loads.
                /// <para>
                /// Two signals must agree, because a copy wrongly stepping aside is a guard switched off.
                /// The nearest ancestor process must be Copilot or Cursor: environment variables are no
                /// use, since a harness started from another one's terminal inherits all of its variables
                /// (observed), and Copilot even sets CLAUDE_PROJECT_DIR for Claude-format hooks. And for a
                /// guard, the payload must lack "transcript_path", which Claude Code always sends and
                /// Copilot's Claude-format payload does not - so Claude Code started from inside a Copilot
                /// session, where the process tree alone would mislead, still decides. Cursor's payload
                /// does carry "transcript_path", so under Cursor both copies still run; that duplicate is
                /// documented rather than engineered away. close-out only warns, so the process tree alone
                /// decides there, and it never reads stdin, which a harness is not obliged to close.
                /// </para>
                /// </remarks>
                private static string? StepsAsideFor(string command, string[] rest, ref TextReader stdin)
                {
                    var harnessIndex = Array.IndexOf(rest, "--harness");
                    var harness = harnessIndex >= 0 && harnessIndex + 1 < rest.Length ? rest[harnessIndex + 1] : null;
                    if (harness != "claude" || command is not ("guard-write" or "guard-version" or "close-out"))
                    {
                        return null;
                    }

                    var runner = HostEnvironment.NearestHarness();
                    if (runner is not ("copilot" or "cursor"))
                    {
                        return null;
                    }

                    if (command == "close-out")
                    {
                        return runner;
                    }

                    var input = stdin.ReadToEnd();
                    stdin = new StringReader(input);
                    return input.Contains("\"transcript_path\"", StringComparison.Ordinal) ? null : runner;
                }

                private const string ImodspecSummaryDenial =
                    "<summary> and <description> in .imodspec are overwritten by the Software Factory from " +
                    "Application Settings on every run - a hand-edit here is discarded silently, not just " +
