        // namespace; ComposeGate joins them into gate.cs behind the single entry point.
        private const string SemVerContent = """
            namespace Intent.Agent.Gate;

            /// <summary>
            /// A parsed semantic version. Comparison follows semver PRECEDENCE, not the version's own
            /// string form - the trap this exists to avoid is that "1.0.0-pre.10" sorts ABOVE
            /// "1.0.0-pre.9" (pre-release identifiers that are both numeric compare numerically), while a
            /// naive string comparison would put "pre.10" first.
            /// </summary>
            public readonly record struct SemVer(int Major, int Minor, int Patch, string? PreRelease)
            {
                public static bool TryParse(string value, out SemVer version)
                {
                    version = default;
                    if (string.IsNullOrWhiteSpace(value))
                    {
                        return false;
                    }

                    var dashIndex = value.IndexOf('-');
                    var core = dashIndex >= 0 ? value[..dashIndex] : value;
                    var preRelease = dashIndex >= 0 ? value[(dashIndex + 1)..] : null;

                    var parts = core.Split('.');
                    if (parts.Length != 3
                        || !int.TryParse(parts[0], out var major)
                        || !int.TryParse(parts[1], out var minor)
                        || !int.TryParse(parts[2], out var patch))
                    {
                        return false;
                    }

                    version = new SemVer(major, minor, patch, string.IsNullOrEmpty(preRelease) ? null : preRelease);
                    return true;
                }

                /// <summary>
                /// Semver precedence comparison. A pre-release sorts BELOW the same core version with no
                /// suffix (so "1.0.0-pre.9" -> "1.0.0" is a legal promotion, not a violation). Pre-release
                /// identifiers compare numerically when both sides of a dot-segment are numeric, and
                /// lexically otherwise - per the semver spec, not a plain string comparison.
                /// </summary>
                public static int ComparePrecedence(SemVer a, SemVer b)
                {
                    var core = a.Major.CompareTo(b.Major);
                    if (core != 0)
                    {
                        return core;
                    }

                    core = a.Minor.CompareTo(b.Minor);
                    if (core != 0)
                    {
                        return core;
                    }

                    core = a.Patch.CompareTo(b.Patch);
                    if (core != 0)
                    {
                        return core;
                    }

                    if (a.PreRelease is null && b.PreRelease is null)
                    {
                        return 0;
                    }

                    if (a.PreRelease is null)
                    {
                        return 1;
                    }

                    if (b.PreRelease is null)
                    {
                        return -1;
                    }

                    return ComparePreReleaseIdentifiers(a.PreRelease, b.PreRelease);
                }

                private static int ComparePreReleaseIdentifiers(string a, string b)
                {
                    var aParts = a.Split('.');
                    var bParts = b.Split('.');
                    var length = Math.Min(aParts.Length, bParts.Length);

                    for (var i = 0; i < length; i++)
                    {
                        var aIsNumeric = int.TryParse(aParts[i], out var aNum);
                        var bIsNumeric = int.TryParse(bParts[i], out var bNum);

                        int cmp;
                        if (aIsNumeric && bIsNumeric)
                        {
                            cmp = aNum.CompareTo(bNum);
                        }
                        else if (aIsNumeric != bIsNumeric)
                        {
                            // A numeric identifier always has lower precedence than an alphanumeric one.
                            cmp = aIsNumeric ? -1 : 1;
                        }
                        else
                        {
                            cmp = string.CompareOrdinal(aParts[i], bParts[i]);
                        }

                        if (cmp != 0)
                        {
                            return cmp;
                        }
                    }

                    return aParts.Length.CompareTo(bParts.Length);
                }

                public override string ToString() => PreRelease is null ? $"{Major}.{Minor}.{Patch}" : $"{Major}.{Minor}.{Patch}-{PreRelease}";
            }
            """;

        private const string HarnessProtocolContent = """
            using System.Text.Json;

            namespace Intent.Agent.Gate;

            /// <summary>
            /// Which AI harness is asking. Claude Code and Codex share a JSON dialect for a
            /// PreToolUse-style decision (confirmed from vendor docs), so they are one case here.
            /// </summary>
            public enum Harness
            {
                ClaudeCodeOrCodex,
                Cursor,
                Kiro,
                Copilot,
                OpenCode,
            }

            /// <summary>
            /// Serializes a gate decision into the harness-specific shape its hook runner expects. Every
            /// harness this gate targets blocks via exit code 2 - that is the one universal signal - and
            /// this class only decides what, if anything, additionally goes to stdout so a human or the
            /// model can read the reason. If real hook wiring shows a different shape, only this file
            /// needs to change.
            ///
            /// Confirmed from vendor documentation:
            ///  - Claude Code / Codex: "hookSpecificOutput.permissionDecision" / "permissionDecisionReason"
            ///    for a PreToolUse-style decision; Claude Code's Stop hook reads "systemMessage" for a
            ///    non-blocking note.
            ///  - Cursor: exit 2 blocks regardless of the JSON body; the body is
            ///    "permission": "allow"|"deny", "agent_message". Cursor fails OPEN on any other non-zero
            ///    exit code, so the caller must always exit exactly 0 or 2, never the runtime's default
            ///    unhandled-exception code.
            ///  - Kiro: blocks purely via exit code 2 plus the reason on stderr - no JSON body is read for
            ///    a PreToolUse deny. On a successful (exit 0) hook, Kiro incorporates stdout directly into
            ///    the agent's context, so a close-out warning is written there as plain text, not JSON.
            /// </summary>
            public static class HarnessProtocol
            {
                public static Harness Parse(string? value) => value?.Trim().ToLowerInvariant() switch
                {
                    "cursor" => Harness.Cursor,
                    "kiro" => Harness.Kiro,
                    "github" or "copilot" => Harness.Copilot,
                    "opencode" => Harness.OpenCode,
                    _ => Harness.ClaudeCodeOrCodex,
                };

                /// <summary>
                /// A deny, used by guard-write and guard-version. Returns what to write to stdout, or
                /// null when nothing should be written there (Kiro and OpenCode - stderr alone carries
                /// the reason).
                /// </summary>
                /// <remarks>
                /// Only ever a DENY. An "allow" decision is never written: Claude Code treats
                /// permissionDecision "allow" as pre-approval and skips its own permission prompt, so
                /// the gate saying "allow" would silently widen what the agent may do. Exit 0 with no
                /// decision leaves the harness's normal permission flow in charge.
                /// </remarks>
                public static string? FormatDeny(Harness harness, string reason) => harness switch
                {
                    Harness.Kiro or Harness.OpenCode => null,
                    Harness.Cursor => Serialize(new { permission = "deny", agent_message = reason }),
                    Harness.Copilot => Serialize(new { permissionDecision = "deny", permissionDecisionReason = reason }),
                    _ => Serialize(new
                    {
                        hookSpecificOutput = new
                        {
                            hookEventName = "PreToolUse",
                            permissionDecision = "deny",
                            permissionDecisionReason = reason,
                        },
                    }),
                };

                /// <summary>
                /// A note for the AGENT on an action that is allowed, with no permission decision, so
                /// the harness's own permission flow is unchanged. Null where the harness has no way to
                /// pass a note to the agent from a pre-tool hook (Copilot, OpenCode).
                /// </summary>
                public static string? FormatAllowWithContext(Harness harness, string context) => harness switch
                {
                    // Cursor's only carrier for a note is its permission response, and "allow" there
                    // pre-approves the action - not worth a reminder.
                    Harness.Copilot or Harness.OpenCode or Harness.Cursor => null,
                    // Kiro adds a successful hook's stdout to the agent's context as it is.
                    Harness.Kiro => context,
                    _ => Serialize(new
                    {
                        hookSpecificOutput = new
                        {
                            hookEventName = "PreToolUse",
                            additionalContext = context,
                        },
                    }),
                };

                /// <summary>
                /// Stop-equivalent, NON-BLOCKING note used by close-out. Close-out never denies (see the
                /// module's deny/warn split), so this only decides how the reason is surfaced when there
                /// is one - callers always exit 0 regardless of what this returns.
                /// </summary>
                public static string FormatWarning(Harness harness, string reason) => harness switch
                {
                    // Kiro adds stdout to the agent's context; OpenCode's plugin relays plain text.
                    Harness.Kiro or Harness.OpenCode => reason,
                    Harness.Cursor => Serialize(new { permission = "allow", agent_message = reason }),
                    _ => Serialize(new { systemMessage = reason }),
                };

                private static string Serialize(object payload) => JsonSerializer.Serialize(payload);
            }
            """;

        private const string GitSupportContent = """
            using System.Diagnostics;
            using System.Text.Json;
            using System.Xml.Linq;

            namespace Intent.Agent.Gate;

            /// <summary>
            /// Finds the root of the git repository (or worktree) containing a given directory, by
            /// walking upward looking for a ".git" entry. In a worktree, ".git" is a file (pointing at
            /// the main repository's worktree metadata) rather than a directory, so both are treated as
            /// a match.
            /// </summary>
            public static class GitRepoLocator
            {
                public static string? FindRepoRoot(string startDirectory)
                {
                    var current = new DirectoryInfo(startDirectory).FullName;

                    while (true)
                    {
                        var dotGit = Path.Combine(current, ".git");
                        if (Directory.Exists(dotGit) || File.Exists(dotGit))
                        {
                            return current;
                        }

                        var parent = Directory.GetParent(current);
                        if (parent is null)
                        {
                            return null;
                        }

                        current = parent.FullName;
                    }
                }
            }

            /// <summary>
            /// Abstraction over "what files changed" and "what a file looked like at HEAD", so gate
            /// logic can be unit-tested against a fake without shelling out to git.
            /// </summary>
            public interface IGitChangeProvider
            {
                /// <summary>
                /// Paths (relative to <paramref name="repoRoot"/>, forward-slash separated, matching
                /// git's own output convention) of files that differ between the working tree and HEAD.
                /// </summary>
                IReadOnlyList<string> GetChangedFiles(string repoRoot);

                /// <summary>
                /// The content of <paramref name="relativePath"/> as it was at HEAD, or null if the path
                /// did not exist at HEAD (e.g. a newly-added file, or a module newly created in this
                /// line of work).
                /// </summary>
                string? TryReadFileAtHead(string repoRoot, string relativePath);
            }

            /// <summary>
            /// Real <see cref="IGitChangeProvider"/> that shells out to git.
            /// </summary>
            public sealed class ProcessGitChangeProvider : IGitChangeProvider
            {
                public IReadOnlyList<string> GetChangedFiles(string repoRoot)
                {
                    // "git diff" alone misses brand-new (untracked) files entirely - a module
                    // created from scratch in this line of work would otherwise be invisible to
                    // the audit below. Union tracked changes against HEAD with untracked files.
                    var changed = GitProcess.Run(repoRoot, "diff", "--name-only", "HEAD");
                    var untracked = GitProcess.Run(repoRoot, "ls-files", "--others", "--exclude-standard");

                    return GitProcess.SplitLines(changed).Concat(GitProcess.SplitLines(untracked))
                        .Distinct(StringComparer.OrdinalIgnoreCase).ToList();
                }

                public string? TryReadFileAtHead(string repoRoot, string relativePath)
                {
                    return GitProcess.Run(repoRoot, "show", $"HEAD:{relativePath}");
                }
            }

            /// <summary>
            /// The single place this gate shells out to git. Every caller gets the same
            /// fail-soft behaviour: a missing "git" executable, or any other failure to start the
            /// process, returns null rather than throwing - callers that can fall back to a
            /// non-git mechanism (see <see cref="ModuleDiscovery"/>) get the chance to.
            /// </summary>
            internal static class GitProcess
            {
                public static string? Run(string repoRoot, params string[] args)
                {
                    var startInfo = new ProcessStartInfo("git")
                    {
                        WorkingDirectory = repoRoot,
                        RedirectStandardOutput = true,
                        RedirectStandardError = true,
                        UseShellExecute = false,
                    };
                    foreach (var arg in args)
                    {
                        startInfo.ArgumentList.Add(arg);
                    }

                    try
                    {
                        using var process = Process.Start(startInfo);
                        if (process is null)
                        {
                            return null;
                        }

                        // Stderr is redirected so git's own messages never leak into the hook's
                        // stderr (which harnesses show to the agent as the block reason) - but a
                        // redirected stream MUST be drained. Outside a repository "git diff HEAD"
                        // writes a multi-kilobyte usage dump there; left unread, the pipe fills,
                        // git blocks writing it, and this blocks waiting for git - a hook that
                        // never returns.
                        var error = process.StandardError.ReadToEndAsync();
                        var output = process.StandardOutput.ReadToEnd();
                        process.WaitForExit();
                        error.Wait();

                        // A non-zero exit (e.g. "show HEAD:path" for a path that did not exist at
                        // HEAD, or git not being a recognised command at all) means no content to
                        // read, not an error worth surfacing to the caller.
                        return process.ExitCode == 0 ? output : null;
                    }
                    catch (Exception)
                    {
                        // git is not installed, not on PATH, or could not be started for some other
                        // reason. Fail soft - the caller decides whether that is fatal or has a
                        // fallback.
                        return null;
                    }
                }

                public static IEnumerable<string> SplitLines(string? output) =>
                    output is null
                        ? []
                        : output.Split('\n').Select(line => line.Trim()).Where(line => line.Length > 0);
            }

            /// <summary>
            /// One entry per Intent Architect application discovered in the repo: its id (from
            /// ".application.config"), and its real OUTPUT root - resolved from that config's own
            /// "location" attribute, which is not always the folder the config itself sits in (a
            /// solution whose workspace root differs from its metadata folder splits the two).
            /// </summary>
            public sealed record DiscoveredApplication(string ApplicationId, string ConfigPath, string OutputRoot);

            /// <summary>
            /// Finds every Intent Architect application in the repo without assuming any particular
            /// folder layout - no hardcoded "Modules/" or similar. A repo laid out differently (a
            /// module author outside this monorepo, or a split metadata/output-root solution like
            /// one built from the Application Template Builder) is still found correctly.
            /// </summary>
            public static class ModuleDiscovery
            {
                private static readonly string[] SkippedDirectoryNames =
                {
                    ".git", "bin", "obj", "node_modules", ".vs", ".idea", ".cache",
                };

                public static IReadOnlyList<DiscoveredApplication> FindAll(string repoRoot)
                {
                    var discovered = new List<DiscoveredApplication>();

                    foreach (var configPath in EnumerateApplicationConfigs(repoRoot))
                    {
                        try
                        {
                            var document = XDocument.Load(configPath);
                            var id = (string?)document.Root?.Attribute("id");
                            if (id is null)
                            {
                                continue;
                            }

                            var location = (string?)document.Root?.Attribute("location") ?? ".";
                            var configDir = Path.GetDirectoryName(configPath)!;
                            var outputRoot = Path.GetFullPath(Path.Combine(configDir, location));

                            discovered.Add(new DiscoveredApplication(id, configPath, outputRoot));
                        }
                        catch (Exception)
                        {
                            // A malformed application.config should not crash discovery - keep looking.
                        }
                    }

                    return discovered;
                }

                /// <summary>
                /// Finds the ".imodspec" belonging to an application's output root. Deliberately
                /// bounded to the root itself and its immediate subfolders (a module's own project
                /// can sit one folder deeper, e.g. "NewModule/NewModule/NewModule.imodspec") rather
                /// than an unbounded recursive search - an application whose output root is an
                /// ancestor of many unrelated modules (e.g. this repo's own dogfood app, whose
                /// output root is the repository root) must correctly report "not a module" rather
                /// than picking up an arbitrary descendant's imodspec. A subfolder carrying its own
                /// ".application.config" is a different application, so its imodspec is never
                /// attributed to this one.
                /// </summary>
                public static string? FindImodspecUnder(string outputRoot)
                {
                    if (!Directory.Exists(outputRoot))
                    {
                        return null;
                    }

                    var atRoot = Directory.EnumerateFiles(outputRoot, "*.imodspec", SearchOption.TopDirectoryOnly).FirstOrDefault();
                    if (atRoot is not null)
                    {
                        return atRoot;
                    }

                    foreach (var subDirectory in Directory.EnumerateDirectories(outputRoot))
                    {
                        var name = Path.GetFileName(subDirectory);
                        if (Array.Exists(SkippedDirectoryNames, skip => string.Equals(skip, name, StringComparison.OrdinalIgnoreCase)))
                        {
                            continue;
                        }

                        if (Directory.EnumerateFiles(subDirectory, "*.application.config", SearchOption.TopDirectoryOnly).Any())
                        {
                            continue;
                        }

                        var match = Directory.EnumerateFiles(subDirectory, "*.imodspec", SearchOption.TopDirectoryOnly).FirstOrDefault();
                        if (match is not null)
                        {
                            return match;
                        }
                    }

                    return null;
                }

                /// <summary>
                /// Attributes each changed file (repo-root-relative, forward-slash) to the discovered
                /// application whose output root contains it, by longest-prefix match - so a file
                /// under a nested module's own output root is attributed there, not to an ancestor
                /// application (e.g. a shared dogfood app) whose root merely happens to contain it
                /// too.
                /// </summary>
                public static IReadOnlyDictionary<DiscoveredApplication, IReadOnlyList<string>> GroupChangedFilesByApplication(
                    string repoRoot, IReadOnlyList<string> normalizedChangedFiles)
                {
                    var applications = FindAll(repoRoot);
                    var grouped = new Dictionary<DiscoveredApplication, List<string>>();

                    foreach (var file in normalizedChangedFiles)
                    {
                        var absolute = Path.GetFullPath(Path.Combine(repoRoot, file));

                        DiscoveredApplication? best = null;
                        var bestLength = -1;
                        foreach (var application in applications)
                        {
                            var root = application.OutputRoot.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
                            var isUnderRoot = absolute.StartsWith(root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)
                                || string.Equals(absolute, root, StringComparison.OrdinalIgnoreCase);

                            if (isUnderRoot && root.Length > bestLength)
                            {
                                best = application;
                                bestLength = root.Length;
                            }
                        }

                        if (best is null)
                        {
                            continue;
                        }

                        if (!grouped.TryGetValue(best, out var list))
                        {
                            list = new List<string>();
                            grouped[best] = list;
                        }

                        list.Add(file);
                    }

                    return grouped.ToDictionary(pair => pair.Key, IReadOnlyList<string> (pair) => pair.Value);
                }

                /// <summary>
                /// The fast, precise path: ask git which ".application.config" files exist, tracked
                /// or not (a module created moments ago and never "git add"-ed must still be found).
                /// Falls back to a bounded filesystem walk only when git itself could not be asked at
                /// all (not on PATH, or this is not a git repository) - never when git ran fine and
                /// simply found nothing.
                /// </summary>
                private static IEnumerable<string> EnumerateApplicationConfigs(string repoRoot)
                {
                    var tracked = GitProcess.Run(repoRoot, "ls-files", "--", "*.application.config");
                    var untracked = GitProcess.Run(repoRoot, "ls-files", "--others", "--exclude-standard", "--", "*.application.config");

                    if (tracked is null && untracked is null)
                    {
                        return EnumerateViaFilesystem(repoRoot);
                    }

                    return GitProcess.SplitLines(tracked).Concat(GitProcess.SplitLines(untracked))
                        .Distinct(StringComparer.OrdinalIgnoreCase)
                        .Select(relative => Path.GetFullPath(Path.Combine(repoRoot, relative.Replace('/', Path.DirectorySeparatorChar))));
                }

                private static IEnumerable<string> EnumerateViaFilesystem(string repoRoot)
                {
                    var results = new List<string>();
                    WalkDirectory(repoRoot, results);
                    return results;
                }

                private static void WalkDirectory(string directory, List<string> results)
                {
                    IEnumerable<string> files;
                    IEnumerable<string> subDirectories;
                    try
                    {
                        files = Directory.EnumerateFiles(directory, "*.application.config", SearchOption.TopDirectoryOnly);
                        subDirectories = Directory.EnumerateDirectories(directory).ToList();
                    }
                    catch (Exception)
                    {
                        return;
                    }

                    results.AddRange(files);

                    foreach (var subDirectory in subDirectories)
                    {
                        var name = Path.GetFileName(subDirectory);
                        if (Array.Exists(SkippedDirectoryNames, skip => string.Equals(skip, name, StringComparison.OrdinalIgnoreCase)))
                        {
                            continue;
                        }

                        WalkDirectory(subDirectory, results);
                    }
                }
            }

            /// <summary>
            /// Extracts a target file path from a PreToolUse-style hook payload on stdin. The exact
            /// JSON shape differs per harness (Claude Code / Codex nest it under "tool_input"; Cursor's
            /// and Kiro's exact shapes are not confirmed from documentation), so this does a tolerant
            /// search: try a short list of candidate key names at the top level, then one level of
            /// nesting inside any object property. A positional CLI argument is accepted as a fallback,
            /// for manual testing or a harness whose payload this doesn't recognise.
            /// </summary>
            public static class StdinPathExtractor
            {
                private static readonly string[] CandidateKeys = ["file_path", "filePath", "path"];

                public static string? Extract(string input, string? positionalArg = null)
                {
                    var fromJson = TryExtractFromJson(input);
                    if (!string.IsNullOrWhiteSpace(fromJson))
                    {
                        return fromJson;
                    }

                    return string.IsNullOrWhiteSpace(positionalArg) ? null : positionalArg;
                }

                private static string? TryExtractFromJson(string input)
                {
                    if (string.IsNullOrWhiteSpace(input))
                    {
                        return null;
                    }

                    try
                    {
                        using var document = JsonDocument.Parse(input);
                        var root = document.RootElement;

                        if (root.ValueKind != JsonValueKind.Object)
                        {
                            return null;
                        }

                        foreach (var key in CandidateKeys)
                        {
                            if (TryGetString(root, key, out var value))
                            {
                                return value;
                            }
                        }

                        foreach (var property in root.EnumerateObject())
                        {
                            if (property.Value.ValueKind != JsonValueKind.Object)
                            {
                                continue;
                            }

                            foreach (var key in CandidateKeys)
                            {
                                if (TryGetString(property.Value, key, out var value))
                                {
                                    return value;
                                }
                            }
                        }

                        return null;
                    }
                    catch (JsonException)
                    {
                        return null;
                    }
                }

                private static bool TryGetString(JsonElement element, string propertyName, out string value)
                {
                    value = string.Empty;

                    if (element.ValueKind == JsonValueKind.Object &&
                        element.TryGetProperty(propertyName, out var property) &&
                        property.ValueKind == JsonValueKind.String)
                    {
                        var raw = property.GetString();
                        if (!string.IsNullOrWhiteSpace(raw))
                        {
                            value = raw;
                            return true;
                        }
                    }

                    return false;
                }
            }

            /// <summary>
            /// One file touched by an "apply_patch" edit, and the lines the patch adds to it.
            /// </summary>
            public sealed record PatchedFile(string Path, string AddedText);

            /// <summary>
            /// Codex edits files through "apply_patch": its tool_input carries the patch TEXT, and the
            /// paths live inside it as "*** Add File: path", "*** Update File: path", "*** Delete File:
            /// path" and "*** Move to: path" lines - there is no file_path field at all. Without this the
            /// write guard found no path, said "no opinion" and allowed every Codex edit, on every OS.
            /// One patch can touch several files, so every one is returned.
            /// </summary>
            public static class ApplyPatchExtractor
            {
                private const string BeginMarker = "*** Begin Patch";

                private static readonly string[] PathMarkers =
                [
                    "*** Add File: ", "*** Update File: ", "*** Delete File: ", "*** Move to: ",
                ];

                /// <summary>The files a patch touches, or null when the payload is not a patch.</summary>
                public static IReadOnlyList<PatchedFile>? Extract(string input)
                {
                    var patch = FindPatchText(input);
                    if (patch is null)
                    {
                        return null;
                    }

                    var files = new List<PatchedFile>();
                    string? currentPath = null;
                    var added = new List<string>();

                    foreach (var rawLine in patch.Replace("\r\n", "\n").Split('\n'))
                    {
                        var marker = Array.Find(PathMarkers, m => rawLine.StartsWith(m, StringComparison.Ordinal));
                        if (marker is not null)
                        {
                            Flush();
                            currentPath = rawLine[marker.Length..].Trim();
                            continue;
                        }

                        if (currentPath is not null && rawLine.StartsWith('+'))
                        {
                            added.Add(rawLine[1..]);
                        }
                    }

                    Flush();
                    return files;

                    void Flush()
                    {
                        if (currentPath is not null)
                        {
                            files.Add(new PatchedFile(currentPath, string.Join("\n", added)));
                        }

                        added.Clear();
                    }
                }

                /// <summary>
                /// The patch text from tool_input (Codex puts it in "command"), searched by content
                /// rather than by key so a renamed field does not silently switch the guard off.
                /// </summary>
                private static string? FindPatchText(string input)
                {
                    if (string.IsNullOrWhiteSpace(input) || !input.Contains(BeginMarker, StringComparison.Ordinal))
                    {
                        return null;
                    }

                    try
                    {
                        using var document = JsonDocument.Parse(input);
                        var root = document.RootElement;
                        if (root.ValueKind != JsonValueKind.Object)
                        {
                            return null;
                        }

                        foreach (var container in new[] { root }.Concat(root.EnumerateObject()
                                     .Where(property => property.Value.ValueKind == JsonValueKind.Object)
                                     .Select(property => property.Value)))
                        {
                            foreach (var property in container.EnumerateObject())
                            {
                                if (property.Value.ValueKind == JsonValueKind.String &&
                                    property.Value.GetString() is { } text &&
                                    text.Contains(BeginMarker, StringComparison.Ordinal))
                                {
                                    return text;
                                }
                            }
                        }

                        return null;
                    }
                    catch (JsonException)
                    {
                        return null;
                    }
                }
            }
