using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Intent.Engine;
using Intent.Metadata.Models;
using Intent.Modules.Common;
using Intent.Modules.Common.Templates;
using Intent.Modules.ModuleBuilder.AI.Guidelines.Templates.RootPrinciples.ModuleBuildingWorkflowMd;
using Intent.RoslynWeaver.Attributes;
using Intent.Templates;
using Intent.Utils;

[assembly: DefaultIntentManaged(Mode.Fully)]
[assembly: IntentTemplate("Intent.ModuleBuilder.ProjectItemTemplate.Partial", Version = "1.0")]

namespace Intent.Modules.ModuleBuilder.AI.Guidelines.Templates.RootPrinciples.CodexInstructionsConfig
{
    [IntentManaged(Mode.Merge, Signature = Mode.Fully)]
    partial class CodexInstructionsConfigTemplate : IntentTemplateBase<object>
    {
        [IntentManaged(Mode.Fully)]
        public const string TemplateId = "Intent.ModuleBuilder.AI.Guidelines.RootPrinciples.CodexInstructionsConfig";

        [IntentManaged(Mode.Merge, Signature = Mode.Fully)]
        public CodexInstructionsConfigTemplate(IOutputTarget outputTarget, object model = null) : base(TemplateId, outputTarget, model)
        {
        }

        private const string BeginMarker = "# >>> Intent Architect module-building workflow - generated by Intent.ModuleBuilder.AI.Guidelines; edits inside this block are overwritten >>>";
        private const string EndMarker = "# <<< Intent Architect module-building workflow <<<";

        // Begin markers this block was written with before, still recognised so a repo moving from
        // Intent.ModuleBuilder.AI.Workflow gets its block rewritten in place rather than left stale.
        private static readonly string[] SupersededBeginMarkers =
        [
            "# >>> Intent Architect module-building workflow - generated by Intent.ModuleBuilder.AI.Workflow; edits inside this block are overwritten >>>",
        ];

        /// <summary>
        /// Codex reads always-on instructions only from AGENTS.md files, which sit outside any
        /// harness folder, and from "developer_instructions" in config.toml. So the workflow reaches
        /// Codex as that key, in the project's ".codex/config.toml".
        /// </summary>
        /// <remarks>
        /// "developer_instructions" takes the text itself, not a file path: "model_instructions_file"
        /// does take a path but REPLACES Codex's own base instructions, and
        /// "project_doc_fallback_filenames" takes bare file names, not paths. Codex honours a
        /// project's ".codex/config.toml" only once the project is trusted - the same condition its
        /// project hooks already need.
        /// </remarks>
        public override bool CanRunTemplate()
        {
            return base.CanRunTemplate() && OutputTarget.Name == ".codex";
        }

        [IntentManaged(Mode.Fully, Body = Mode.Ignore)]
        public override ITemplateFileConfig GetTemplateFileConfig()
        {
            return new TemplateFileConfig(fileName: "config", fileExtension: "toml", relativeLocation: "");
        }

        [IntentManaged(Mode.Fully, Body = Mode.Ignore)]
        public override string TransformText()
        {
            // Merged, never owned: config.toml is where the developer keeps their own Codex settings.
            // Only the marked block is ours - added at the top, where a TOML key must sit before any
            // [table], and rewritten in place on every run. A developer_instructions key of their own
            // is left alone, since TOML rejects a key defined twice.
            var path = Path.Combine(OutputTarget.Location, "config.toml");
            var existing = File.Exists(path) ? File.ReadAllText(path) : string.Empty;
            var block = Block();

            var begin = SupersededBeginMarkers.Prepend(BeginMarker)
                .Select(marker => existing.IndexOf(marker, StringComparison.Ordinal))
                .FirstOrDefault(index => index >= 0, -1);
            var end = existing.IndexOf(EndMarker, StringComparison.Ordinal);
            if (begin >= 0 && end > begin)
            {
                return existing[..begin] + block + existing[(end + EndMarker.Length)..];
            }

            if (DefinesDeveloperInstructions(existing))
            {
                Logging.Log.Warning(
                    $"{TemplateId}: '{path}' already sets developer_instructions, so the module-building workflow was not added " +
                    "to it. Codex will not see the workflow instructions until that key is removed or carries them.");
                return existing;
            }

            return existing.Length == 0 ? block + "\n" : block + "\n\n" + existing;
        }

        private string Block()
        {
            var markdown = new ModuleBuildingWorkflowMdTemplate(OutputTarget).MarkdownFile.ToString();
            var body = StripFrontMatter(markdown).Trim();
            if (body.Contains("'''", StringComparison.Ordinal))
            {
                throw new InvalidOperationException("The workflow instructions contain ''' and cannot be written as a TOML literal string.");
            }

            // A TOML multi-line literal string: no escapes, so the Markdown goes in exactly as it is.
            return string.Join("\n", BeginMarker, "developer_instructions = '''", body, "'''", EndMarker);
        }

        private static string StripFrontMatter(string markdown)
        {
            var text = markdown.Replace("\r\n", "\n");
            if (!text.StartsWith("---\n", StringComparison.Ordinal))
            {
                return text;
            }

            var close = text.IndexOf("\n---", 4, StringComparison.Ordinal);
            return close < 0 ? text : text[(close + 4)..];
        }

        private static bool DefinesDeveloperInstructions(string toml)
        {
            foreach (var line in toml.Replace("\r\n", "\n").Split('\n'))
            {
                var trimmed = line.TrimStart();
                if (trimmed.StartsWith("[", StringComparison.Ordinal))
                {
                    // Only top-level keys count; anything after the first table belongs to that table.
                    return false;
                }

                if (trimmed.StartsWith("developer_instructions", StringComparison.Ordinal))
                {
                    return true;
                }
            }

            return false;
        }
    }
}
