        private const string ScriptContent = """
            #!/usr/bin/env dotnet
            #:property PublishAot=false
            #:property ImportDirectoryBuildTargets=false
            #:property LangVersion=latest
            #:property Nullable=enable
            #:property ImplicitUsings=enable
            #:property TreatWarningsAsErrors=false
            #:property RunAnalyzers=false
            #:property EnforceCodeStyleInBuild=false
            #:property GenerateDocumentationFile=false

            // Sets, verifies or exports a module's package icon without printing the icon's value.
            // Bundled with the module-svg-icon skill, generated by Intent.ModuleBuilder.AI.Guidelines - regenerate rather than edit.
            //
            // Runs on any .NET 10 SDK or later, from any folder:
            //   dotnet run <this file> -- --check
            //   dotnet run <this file> -- --module <module folder> --svg <approved icon>.svg
            //   dotnet run <this file> -- --module <module folder> --svg <approved icon>.svg --verify [--imod <built>.imod]
            //   dotnet run <this file> -- --module <module folder> --export <temp folder>/current.svg
            //
            // Point it at the module's folder, the one holding its .imodspec. No Intent Architect tool takes the package
            // icon from a file, and the base64 value is too large to pass through an agent's context, so this file reads
            // and writes it. It prints lengths, hashes and fixed messages only, never the value, and reports an unexpected
            // error by type and line, because a .NET error message can carry its arguments, and here those include the
            // data URI.
            //
            // The icon is stored in the module's Intent Architect application settings (the .application.config in the
            // module folder): a root, attribute-less <icon> holding a data URI, with a sibling <iconType>. The Software
            // Factory regenerates the .imodspec's <iconUrl> from it.
            //
            // --svg: stores the SVG as the package icon, as a data URI with <iconType> UrlImagePath, adding <iconType> if
            // absent. It changes nothing unless the settings hold exactly one root <icon> and at most one <iconType>, and
            // it keeps the file's encoding and line endings.
            // --verify --svg: prints the SHA-256 of the data URI built from the SVG, of the stored icon, of the module's
            // .imodspec icon and, with --imod, of the icon in the .imodspec packaged inside the .imod. Exits 1 unless they
            // all match.
            // --export: writes the current package icon to a file so it can be rendered. An SVG is written to the path
            // given; another embedded image type gets that type's extension instead. A built-in icon, which is a name
            // rather than an image, is not exported.
            // --check: says the file can run, and builds it, so the first real run is quick.
            //
            // Exit codes: 0 done, 1 --verify found a mismatch, 2 stopped with nothing changed.
            //
            // Builds inside any repository: a file-based app picks up the Directory.Build.props, Directory.Build.targets
            // and .editorconfig above it. The #:property lines above skip the targets, override the props' language,
            // nullable, warnings-as-errors and analyzer settings, and turn analyzers off; the code is free of compiler
            // warnings. A props file that adds items of its own (a global using, a package) can still break the build;
            // then copy this file to a folder outside the repository and run the copy.

            using System.IO.Compression;
            using System.Security.Cryptography;
            using System.Text;
            using System.Text.RegularExpressions;

            return SetModuleIcon.Program.Run(args);

            namespace SetModuleIcon
            {
                internal static class Program
                {
                    private const string Usage =
                        "Usage: dotnet run <this file> -- --module <module folder> --svg <approved icon>.svg [--verify [--imod <built>.imod] [--imodspec <file>]]\n" +
                        "   or: dotnet run <this file> -- --module <module folder> --export <file>.svg\n" +
                        "   or: dotnet run <this file> -- --check";

                    public static int Run(string[] args)
                    {
                        try
                        {
                            return Execute(Options.Parse(args));
                        }
                        catch (StopException stop)
                        {
                            Console.Error.WriteLine("set-module-icon: " + stop.Message);
                            return 2;
                        }
                        catch (Exception ex)
                        {
                            Console.Error.WriteLine($"set-module-icon: unexpected {ex.GetType().Name}{LineOf(ex)}. Nothing more is reported, so the icon's value cannot leak.");
                            return 2;
                        }
                    }

                    private static int Execute(Options options)
                    {
                        if (options.Help)
                        {
                            Console.WriteLine(Usage);
                            return 0;
                        }

                        if (options.Check)
                        {
                            Console.WriteLine($"set-module-icon is ready (.NET {Environment.Version}).");
                            return 0;
                        }

                        if (options.Export != null && (options.Svg != null || options.Verify))
                        {
                            throw new StopException("Use --export on its own, or --svg to set or verify the icon.");
                        }

                        if (options.Export == null && options.Svg == null)
                        {
                            throw new StopException("Pass --svg <approved icon>.svg to set or verify the icon, or --export <file>.svg to export the current one.\n" + Usage);
                        }

                        if (options.Module == null)
                        {
                            throw new StopException("Pass --module <module folder>, the module's own folder, the one holding its .imodspec.");
                        }

                        if (!Directory.Exists(options.Module))
                        {
                            throw new StopException("Module folder not found: " + options.Module);
                        }

                        var module = Path.GetFullPath(options.Module);
                        var configs = Directory.GetFiles(module, "*.application.config", SearchOption.TopDirectoryOnly);
                        if (configs.Length != 1)
                        {
                            throw new StopException($"Expected the module's Intent Architect application in {module}, found {configs.Length}. Pass the module's own folder, the one holding its .imodspec; if it already is, report this to the developer. Nothing was changed.");
                        }

                        var config = configs[0];
                        var text = File.ReadAllText(config);
                        var icon = Regex.Matches(text, "<icon>([^<]*)</icon>");
                        var type = Regex.Matches(text, "<iconType>[^<]*</iconType>");
                        if (icon.Count != 1 || type.Count > 1)
                        {
                            throw new StopException($"The module's package icon setting is not in the expected shape (found {icon.Count} icon and {type.Count} icon-type entries). Nothing was changed; report this to the developer.");
                        }

                        if (options.Export != null)
                        {
                            return Export(icon[0].Groups[1].Value, options.Export);
                        }

                        if (!File.Exists(options.Svg))
                        {
                            throw new StopException("File not found: " + options.Svg);
                        }

                        var uri = "data:image/svg+xml;base64," + Convert.ToBase64String(File.ReadAllBytes(options.Svg!));

                        return options.Verify
                            ? Verify(module, uri, icon[0].Groups[1].Value, options.Imodspec, options.Imod)
                            : Set(config, text, icon[0], type, uri);
                    }

                    private static int Export(string current, string exportPath)
                    {
                        if (current.Length == 0)
                        {
                            throw new StopException("The module has no package icon. Nothing was exported.");
                        }

                        var embedded = Regex.Match(current, @"^data:image/([A-Za-z0-9.+-]+);base64,([A-Za-z0-9+/=\s]*)$");
                        if (!embedded.Success)
                        {
                            throw new StopException("The current package icon is a built-in icon, not an embedded image. Nothing was exported.");
                        }

                        var target = Path.GetFullPath(exportPath);
                        var mime = embedded.Groups[1].Value.ToLowerInvariant();
                        if (mime != "svg+xml")
                        {
                            var extension = mime switch
                            {
                                "jpeg" => ".jpg",
                                "x-icon" => ".ico",
                                _ => "." + Regex.Replace(mime, "[^a-z0-9]", ""),
                            };
                            target = Path.ChangeExtension(target, extension);
                        }

                        var folder = Path.GetDirectoryName(target);
                        if (!string.IsNullOrEmpty(folder))
                        {
                            Directory.CreateDirectory(folder);
                        }

                        var bytes = Convert.FromBase64String(embedded.Groups[2].Value);
                        File.WriteAllBytes(target, bytes);
                        Console.WriteLine(mime == "svg+xml"
                            ? $"Exported the current package icon ({bytes.Length} bytes, SVG) to {target}."
                            : $"The current package icon is a {mime} image, not an SVG. Exported it ({bytes.Length} bytes) to {target}.");
                        return 0;
                    }

                    private static int Verify(string module, string uri, string stored, string? imodspec, string? imod)
                    {
                        if (imodspec == null)
                        {
                            var specs = Directory.GetFiles(module, "*.imodspec", SearchOption.TopDirectoryOnly);
                            if (specs.Length != 1)
                            {
                                throw new StopException($"Found {specs.Length} .imodspec files in the module folder; pass --imodspec.");
                            }

                            imodspec = specs[0];
                        }
                        else if (!File.Exists(imodspec))
                        {
                            throw new StopException("File not found: " + imodspec);
                        }

                        var rows = new List<KeyValuePair<string, string>>
                        {
                            new("approved SVG", Hash(uri)),
                            new("stored icon", Hash(stored)),
                            new(".imodspec", Hash(IconUrl(File.ReadAllText(imodspec)))),
                        };

                        if (imod != null)
                        {
                            if (!File.Exists(imod))
                            {
                                throw new StopException("File not found: " + imod);
                            }

                            using var zip = ZipFile.OpenRead(imod);
                            var entries = zip.Entries.Where(e => e.FullName.EndsWith(".imodspec", StringComparison.OrdinalIgnoreCase)).ToList();
                            if (entries.Count != 1)
                            {
                                throw new StopException($"Found {entries.Count} .imodspec entries in the .imod.");
                            }

                            using var reader = new StreamReader(entries[0].Open());
                            rows.Add(new("packaged .imod", Hash(IconUrl(reader.ReadToEnd()))));
                        }

                        foreach (var row in rows)
                        {
                            Console.WriteLine($"{row.Key,-20} {row.Value}");
                        }

                        var mismatched = rows.Where(r => r.Value != rows[0].Value).Select(r => r.Key).ToList();
                        if (mismatched.Count > 0)
                        {
                            Console.WriteLine($"Mismatch: {string.Join(", ", mismatched)}.");
                            return 1;
                        }

                        Console.WriteLine(imod == null ? "All checked values match. The .imod was not checked: pass --imod." : "All four match.");
                        return 0;
                    }

                    private static int Set(string config, string text, Match icon, MatchCollection type, string uri)
                    {
                        var bytes = File.ReadAllBytes(config);
                        var bom = bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF;
                        var newline = text.Contains("\r\n") ? "\r\n" : "\n";
                        var indent = Regex.Match(text, @"(?m)^([ \t]*)<icon>").Groups[1].Value;

                        var replacement = "<icon>" + uri + "</icon>";
                        text = text.Replace(icon.Value, replacement);
                        text = type.Count == 1
                            ? text.Replace(type[0].Value, "<iconType>UrlImagePath</iconType>")
                            : text.Replace(replacement, replacement + newline + indent + "<iconType>UrlImagePath</iconType>");

                        File.WriteAllText(config, text, new UTF8Encoding(bom));
                        Console.WriteLine($"Set the module's package icon ({uri.Length} characters). Run the Software Factory to regenerate the .imodspec from it.");
                        return 0;
                    }

                    private static string Hash(string? value)
                    {
                        if (string.IsNullOrEmpty(value))
                        {
                            return "(missing)";
                        }

                        using var sha = SHA256.Create();
                        return Convert.ToHexString(sha.ComputeHash(Encoding.UTF8.GetBytes(value)));
                    }

                    private static string? IconUrl(string manifest)
                    {
                        var match = Regex.Match(manifest, "<iconUrl>([^<]*)</iconUrl>");
                        return match.Success ? match.Groups[1].Value : null;
                    }

                    private static string LineOf(Exception ex)
                    {
                        var frame = new System.Diagnostics.StackTrace(ex, true).GetFrames()
                            .FirstOrDefault(f => f.GetFileLineNumber() > 0);
                        return frame == null ? "" : $" at line {frame.GetFileLineNumber()}";
                    }
                }

                internal sealed class Options
                {
                    public string? Module { get; private set; }
                    public string? Svg { get; private set; }
                    public string? Export { get; private set; }
                    public string? Imodspec { get; private set; }
                    public string? Imod { get; private set; }
                    public bool Verify { get; private set; }
                    public bool Check { get; private set; }
                    public bool Help { get; private set; }

                    public static Options Parse(string[] args)
                    {
                        var options = new Options();
                        for (var i = 0; i < args.Length; i++)
                        {
                            // PowerShell-style -Module is accepted as well as --module, so an older command still works.
                            var name = args[i].TrimStart('-').ToLowerInvariant();
                            switch (name)
                            {
                                case "verify": options.Verify = true; break;
                                case "check": options.Check = true; break;
                                case "help": case "h": case "?": options.Help = true; break;
                                case "module": options.Module = Value(args, ref i); break;
                                case "svg": options.Svg = Value(args, ref i); break;
                                case "export": options.Export = Value(args, ref i); break;
                                case "imodspec": options.Imodspec = Value(args, ref i); break;
                                case "imod": options.Imod = Value(args, ref i); break;
                                default: throw new StopException($"Unknown argument '{args[i]}'. Nothing was changed.");
                            }
                        }

                        return options;
                    }

                    private static string Value(string[] args, ref int i)
                    {
                        if (i + 1 >= args.Length || args[i + 1].StartsWith("--", StringComparison.Ordinal))
                        {
                            throw new StopException($"{args[i]} needs a value. Nothing was changed.");
                        }

                        return args[++i];
                    }
                }

                internal sealed class StopException : Exception
                {
                    public StopException(string message) : base(message)
                    {
                    }
                }
            }
            """;
    }
